      <div class="page">
        <div class="kicker">Teach your eyes the grammar</div>
        <h1>Reading the Labyrinth</h1><div class="rule"></div>
        <p>Every dungeon is generated from a new deterministic layout. It is a multi-floor maze, not several independent floors stacked together.</p>
        <ul>
          <li>Stairs are meaningful connections. Remember which floor they join.</li>
          <li>Colored gates divide the expedition into permanent chapters.</li>
          <li>Side branches can be dangerous precisely because they are optional.</li>
          <li>Open gates stay open.</li>
          <li>The physical maze, the minimap and your own memory are three different navigation tools.</li>
        </ul>
        <h3>About the Map</h3>
        <p>During Dungeons 1–20, deployed living players can consult the map by spending Magic. From Dungeon 21 onward, the production map no longer answers.</p>
        <p class="hand">“By then, supposedly, you know better.” — somebody optimistic</p>
