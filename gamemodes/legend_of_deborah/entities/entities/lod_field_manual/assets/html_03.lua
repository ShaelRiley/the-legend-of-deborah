        <h1>Going Together</h1><div class="rule"></div>
        <ul>
          <li>Up to <b>four</b> expeditioners can be active.</li>
          <li>Keycards and gate progress are <b>team-wide</b>.</li>
          <li>Lives, Magic, weapons, ammunition and individualized loot remain <b>personal</b>.</li>
          <li>Friendly fire is off.</li>
          <li>Teammates do not physically block one another.</li>
          <li>A newly admitted player stages first, claims a personal starter, then deploys through the portal.</li>
          <li>Campaign identity persists through reconnects; disconnecting is not a vending machine for fresh lives or a new starter.</li>
        </ul>
        <p>The dungeon scales its pressure to the connected cooperative party when a new level is planned. The maze itself does not become larger simply because more people arrived.</p>
