        <h1>The Legend</h1><div class="rule"></div>
        <h2>Rescue is victory. Rescue is not release.</h2>
        <p>When Deborah is reached, the current dungeon ends. The team is given a short reprieve. Then the labyrinth gathers itself again at a deeper level.</p>
        <p>Deborah has been rescued before.</p>
        <p>She occasionally speaks as if she knows this.</p>
        <p>No official explanation has survived long enough to be printed here.</p>
        <div class="silhouette">[ A shipping-container fortress beneath a midnight sky ]</div>
