        <h1>The Legend</h1><div class="rule"></div>
        <h2>Deborah is imprisoned.</h2>
        <p>Somewhere beneath the open night of Flatgrass stands a prison that has no business being there: freight containers, steel floors, emergency barriers, colored locks and hostile things that behave as though the whole construction were ancient law.</p>
        <p>Deborah is inside.</p>
        <p>The prison rebuilds itself. Corridors move between expeditions. Stairways rise into different chambers. A room remembered perfectly may never exist again.</p>
        <p>The people sent to retrieve her are familiar faces from a world already accustomed to impossible circumstances.</p>
        <div class="diagram"><b>YOUR PURPOSE IS SIMPLE:</b><br>Enter. Descend. Open the way. Reach Deborah.</div>
        <div class="note"><strong>A WORD TO THE WISE:</strong> The labyrinth is procedural. Its promises are not.</div>
