    <article class="source-page" data-title="The Dice Decide">
      <div class="page">
        <div class="kicker">Combat is chance with a memory</div>
        <h1>The Dice Decide</h1><div class="rule"></div>
        <p>Weapons do not simply deal one fixed number. They roll damage dice.</p>
        <div class="columns">
          <div class="diagram"><span class="die">1d4</span><p><b>1d4</b> means: roll one four-sided die.</p></div>
          <div class="diagram"><span class="die">2d6</span><p><b>2d6</b> means: roll two six-sided dice and add them.</p></div>
        </div>
        <h3>Exploding Dice</h3>
        <p>Some attacks can explode. A sufficiently high die result earns another die, which may itself explode again. Lucky chains are loud on purpose.</p>
        <p>The same general law applies to monsters: they also roll their damage, and many roll their health when they enter the world.</p>
        <div class="note"><strong>DEBORAH'S NOTE:</strong> Never become emotionally attached to an expected value.</div>
