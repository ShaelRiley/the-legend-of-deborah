function Effects:MagicRecoveryProfile(state)
    return {
        feedbackLoop = owns(state, "INT_FEEDBACK_LOOP"),
        feedbackLoopPerCastCap = owns(state, "INT_FEEDBACK_LOOP") and 6 or 0,
        arcRecovery = owns(state, "INT_ARC_RECOVERY"),
        arcRecoveryMagic = owns(state, "INT_ARC_RECOVERY") and 5 or 0,
        arcRecoveryCooldownSeconds = owns(state, "INT_ARC_RECOVERY") and 2.0 or 0
    }
end

-- Pure ordered transitions. The Force Shout authority owns committed-cast and
-- Magic resource state; these helpers own only the two feat magnitudes/caps.
function Effects:ResolveFeedbackLoop(enabled, continuationDice, alreadyRestored, currentMagic)
    local continuations = math.max(0, math.floor(tonumber(continuationDice) or 0))
    local used = math.Clamp(math.floor(tonumber(alreadyRestored) or 0), 0, 6)
    local magic = math.Clamp(tonumber(currentMagic) or 0, 0, 100)
    if enabled ~= true or continuations <= 0 or used >= 6 or magic >= 100 then
        return magic, 0, used
    end
    local restored = math.min(continuations, 6 - used, 100 - magic)
    return magic + restored, restored, used + restored
end

function Effects:ResolveArcRecovery(enabled, defeatedAI, now, readyAt, currentMagic)
    local magic = math.Clamp(tonumber(currentMagic) or 0, 0, 100)
    local at = tonumber(now) or 0
    local ready = tonumber(readyAt) or 0
    if enabled ~= true or defeatedAI ~= true or at < ready or magic >= 100 then
        return magic, 0, ready, false
    end
    local restored = math.min(5, 100 - magic)
    return magic + restored, restored, at + 2.0, true
end

function Effects:ApplyFeedbackLoop(actor, resourceState, continuationDice, alreadyRestored)
    local profile = self:MagicRecoveryProfile(Rules:ProgressionState(actor))
    local current = tonumber(resourceState and resourceState.magic) or 0
    local magic, restored, used = self:ResolveFeedbackLoop(
        profile.feedbackLoop, continuationDice, alreadyRestored, current)
    if resourceState then resourceState.magic = magic end
    local stats = self.MagicRecoveryStats
    stats.continuationDice = (stats.continuationDice or 0)
        + math.max(0, math.floor(tonumber(continuationDice) or 0))
    stats.feedbackLoopRestored = (stats.feedbackLoopRestored or 0) + restored
    return restored, used
end

function Effects:ApplyArcRecovery(actor, resourceState, defeatedAI, now)
    local profile = self:MagicRecoveryProfile(Rules:ProgressionState(actor))
    local current = tonumber(resourceState and resourceState.magic) or 0
    local readyAt = tonumber(resourceState and resourceState.arcRecoveryReadyAt) or 0
    local magic, restored, nextReady, triggered = self:ResolveArcRecovery(
        profile.arcRecovery, defeatedAI, now, readyAt, current)
    if resourceState then
        resourceState.magic = magic
        resourceState.arcRecoveryReadyAt = nextReady
    end
    local stats = self.MagicRecoveryStats
    if defeatedAI then stats.magicKills = (stats.magicKills or 0) + 1 end
    if triggered then
        stats.arcRecoveryRestored = (stats.arcRecoveryRestored or 0) + restored
    elseif defeatedAI and profile.arcRecovery and (tonumber(now) or 0) < readyAt then
        stats.arcRecoveryCooldownRejects = (stats.arcRecoveryCooldownRejects or 0) + 1
    end
    return restored, triggered
end

