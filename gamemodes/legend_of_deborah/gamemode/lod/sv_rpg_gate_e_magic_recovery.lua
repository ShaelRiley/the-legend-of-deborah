end)

concommand.Add("lod_rpg_gate_e_magic_recovery_status", function(ply)
    if not developerAllowed(ply) or not IsValid(ply) then return end
    local run = LOD.RunManager
    local ps = run and run.GetPlayerState and run:GetPlayerState(ply) or nil
    local profile = Effects:MagicRecoveryProfile(Rules:ProgressionState(ply))
    local stats = Effects.MagicRecoveryStats
    local arcRemaining = math.max(0, (tonumber(ps and ps.arcRecoveryReadyAt) or 0) - CurTime())
    local baselineOK = not profile.feedbackLoop and not profile.arcRecovery
        and (stats.feedbackLoopRestored or 0) == 0 and (stats.arcRecoveryRestored or 0) == 0
    local featOK = profile.feedbackLoop and profile.arcRecovery
        and (stats.feedbackLoopRestored or 0) >= 1
        and (stats.magicKills or 0) >= 1 and (stats.arcRecoveryRestored or 0) >= 1
    local line = string.format(
        "feedback=%s continuations=%d restored=%d cap=6 arc=%s kills=%d restored=%d cooldownRejects=%d readyIn=%.2fs magic=%.2f acceptance=%s",
        tostring(profile.feedbackLoop), stats.continuationDice or 0,
        stats.feedbackLoopRestored or 0, tostring(profile.arcRecovery),
        stats.magicKills or 0, stats.arcRecoveryRestored or 0,
        stats.arcRecoveryCooldownRejects or 0, arcRemaining,
        tonumber(ps and ps.magic) or 0, (baselineOK or featOK) and "PASS" or "WAITING")
    print("[LOD:RPG-E] " .. line)
    ply:ChatPrint(line)
end)

concommand.Add("lod_rpg_gate_e_magic_recovery_testkit", function(ply, _, args)
    if not developerAllowed(ply) or not IsValid(ply) or not ply:Alive() then return end
    local enabled = tonumber(args[1]) == 1
    local ps, message = configurePlayer(ply, enabled)
    if not ps then ply:ChatPrint(message) return end
    resetTelemetry(enabled)
    local prepared = 0
    for _, hostile in ipairs(LOD.HostileRegistry and LOD.HostileRegistry:List() or {}) do
        if IsValid(hostile) and hostile.LODHostile and not hostile.LODDead and hostile:Health() > 0 then
            hostile:SetHealth(1)
            prepared = prepared + 1
        end
    end
    local line = string.format(
        "Batch 12 %s: Magic=30; %d one-HP targets. Aim, RMB, wait 1s, then run magic_recovery_status; rerun if no continuation rolled.",
        enabled and "FEATS" or "BASELINE", prepared)
    print("[LOD:RPG-E] " .. line)
    ply:ChatPrint(line)
end)

