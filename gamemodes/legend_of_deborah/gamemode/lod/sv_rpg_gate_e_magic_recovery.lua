function Effects:ValidateMagicRecoveryFamilies()
    local errors = {}
    local function expect(ok, message)
        if not ok then errors[#errors + 1] = message end
    end
    local feedback = Feats.INT_FEEDBACK_LOOP
    local arc = Feats.INT_ARC_RECOVERY
    expect(feedback and feedback.abilityRequirements.int == 15, "Feedback Loop INT 15")
    expect(arc and arc.abilityRequirements.int == 17, "Arc Recovery INT 17")
    expect(feedback and feedback.effectHandlerId == "magic_continuation_recovery",
        "Feedback Loop handler")
    expect(arc and arc.effectHandlerId == "magic_kill_recovery", "Arc Recovery handler")

    local baseline = self:MagicRecoveryProfile({featIds = {}})
    local both = self:MagicRecoveryProfile({featIds = {
        "INT_FEEDBACK_LOOP", "INT_ARC_RECOVERY"
    }})
    expect(not baseline.feedbackLoop and not baseline.arcRecovery,
        "baseline recovery disabled")
    expect(both.feedbackLoop and both.feedbackLoopPerCastCap == 6,
        "Feedback Loop profile")
    expect(both.arcRecovery and both.arcRecoveryMagic == 5
        and both.arcRecoveryCooldownSeconds == 2.0, "Arc Recovery profile")

    local magic, restored, used = self:ResolveFeedbackLoop(true, 8, 0, 70)
    expect(magic == 76 and restored == 6 and used == 6,
        "Feedback Loop six-Magic committed-cast cap")
    magic, restored, used = self:ResolveFeedbackLoop(true, 2, 5, 99)
    expect(magic == 100 and restored == 1 and used == 6,
        "Feedback Loop universal Magic ceiling")
    magic, restored = self:ResolveFeedbackLoop(false, 8, 0, 70)
    expect(magic == 70 and restored == 0, "baseline continuation isolation")

    local nextReady, triggered
    magic, restored, nextReady, triggered = self:ResolveArcRecovery(true, true, 10, 0, 70)
    expect(magic == 75 and restored == 5 and nextReady == 12 and triggered,
        "Arc Recovery kill restore and cooldown")
    magic, restored, nextReady, triggered = self:ResolveArcRecovery(true, true, 11, nextReady, magic)
    expect(magic == 75 and restored == 0 and nextReady == 12 and not triggered,
        "Arc Recovery cooldown rejects clustered kill")
    magic, restored, nextReady, triggered = self:ResolveArcRecovery(true, true, 12, nextReady, 98)
    expect(magic == 100 and restored == 2 and nextReady == 14 and triggered,
        "Arc Recovery caps at 100 Magic")
    return #errors == 0, errors
end

if Validation and not Validation.LODGateEMagicRecoveryWrapped then
    Validation.LODGateEMagicRecoveryWrapped = true
    local base = Validation.Run
    function Validation:Run(printResult)
        local baseOK, errors = base(self, false)
        errors = errors or {}
        local featOK, featErrors = Effects:ValidateMagicRecoveryFamilies()
        for _, message in ipairs(featErrors or {}) do
            errors[#errors + 1] = "Gate E Magic recovery: " .. message
        end
        local ok = baseOK and featOK and #errors == 0
        if printResult ~= false then
            if ok then
                print(string.format(
                    "[LOD:RPG] core RPG validation PASS — gate=%s gameplayEnabled=%s gateEMagicRecovery=true",
                    tostring(RPG.ImplementationGate), tostring(RPG.GameplayEnabled)))
            else
                ErrorNoHalt("[LOD:RPG] core RPG validation FAILED (" .. #errors .. " error(s))\n")
                for _, message in ipairs(errors) do
                    ErrorNoHalt("[LOD:RPG]  - " .. message .. "\n")
                end
            end
        end
        return ok, errors
    end
end

local function developerAllowed(ply)
    local cv = GetConVar("lod_developer_mode")
    return cv and cv:GetBool() and (not IsValid(ply) or ply:IsAdmin())
end

local function configurePlayer(ply, enabled)
    local run = LOD.RunManager
    local ps = run and run.GetPlayerState and run:GetPlayerState(ply) or nil
    local state = ps and ps.progressionState or nil
    if not state then return nil, "RPG progression state is unavailable." end
    local kept = {}
    for _, id in ipairs(state.featIds or {}) do
        if not TEST_IDS[id] then kept[#kept + 1] = id end
    end
    state.featIds = kept
    state.featStackCounts = state.featStackCounts or {}
    for id in pairs(TEST_IDS) do state.featStackCounts[id] = nil end
    if enabled then
        for _, id in ipairs({"INT_FEEDBACK_LOOP", "INT_ARC_RECOVERY"}) do
            state.featIds[#state.featIds + 1] = id
            state.featStackCounts[id] = 1
        end
    end
    Progression:_RecomputeProgressionState(state)
    Progression:SyncPlayer(ply)
    ps.magic = 30
    ps.arcRecoveryReadyAt = 0
    local magic = LOD.Magic
    if magic and magic.NextCast then magic.NextCast[ply] = 0 end
    if magic and magic._Sync then magic:_Sync(ply, ps) end
    if run.MarkUnranked then run:MarkUnranked("Gate E Magic recovery feat test") end
    return ps
end

local function resetTelemetry(enabled)
    local stats = Effects.MagicRecoveryStats
    stats.continuationDice = 0
    stats.feedbackLoopRestored = 0
    stats.magicKills = 0
    stats.arcRecoveryRestored = 0
    stats.arcRecoveryCooldownRejects = 0
    stats.castsWithFeedback = 0
    stats.expectedEnabled = enabled == true
end

