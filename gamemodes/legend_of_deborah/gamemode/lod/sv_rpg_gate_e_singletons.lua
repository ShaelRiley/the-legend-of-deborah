if not Progression.LODGateEMagnumCapabilityWrapped then
    Progression.LODGateEMagnumCapabilityWrapped = true
    local baseHasCapability = Progression._HasCapability
    function Progression:_HasCapability(ps, state, tag)
        if tag == "magnum" then
            if ps and ps.starterWeaponClass == "weapon_357" then return true end
            for _, weaponState in ipairs(ps and ps.inventory and ps.inventory.weapons or {}) do
                if weaponState.class == "weapon_357" then return true end
            end
            local run = LOD.RunManager
            if player and isfunction(player.GetAll) and run and run.GetPlayerState then
                for _, actor in ipairs(player.GetAll()) do
                    if IsValid(actor) and run:GetPlayerState(actor) == ps
                        and actor.HasWeapon and actor:HasWeapon("weapon_357")
                    then
                        return true
                    end
                end
            end
            return false
        end
        return baseHasCapability(self, ps, state, tag)
    end
end

local function owns(state, featId)
    for _, ownedId in ipairs(state and state.featIds or {}) do
        if ownedId == featId then return true end
    end
    return false
end

local function stateFor(actorOrState)
    if istable(actorOrState) and actorOrState.featIds then return actorOrState end
    return Rules:ProgressionState(actorOrState)
end

function Effects:SingletonProfile(state)
    local springHeel = owns(state, "DEX_SPRING_HEEL")
    local deadeye = owns(state, "DEX_MAGNUM_DEADEYE")
    local longReach = owns(state, "STR_MELEE_REACH")
    local russianAsset = owns(state, "CON_RUSSIAN_ASSET")
    return {
        springHeel = springHeel,
        jumpHeightMultiplier = springHeel and SPRING_HEEL_HEIGHT_MULTIPLIER or 1,
        jumpImpulseMultiplier = springHeel and SPRING_HEEL_IMPULSE_MULTIPLIER or 1,
        deadeye = deadeye,
        aimHoldSeconds = 0.50,
        magnumAimHoldSeconds = 0.50,
        longReach = longReach,
        meleeReachMultiplier = longReach and LONG_REACH_MULTIPLIER or 1,
        russianAsset = russianAsset,
        tetrisOverfillMultiplier = russianAsset and RUSSIAN_ASSET_REWARD_MULTIPLIER or 1,
        deathTetrisMaxSeconds = russianAsset and RUSSIAN_ASSET_DEATH_TETRIS_SECONDS
            or BASE_DEATH_TETRIS_SECONDS
    }
end

