    stats.meleeSwings = (stats.meleeSwings or 0) + 1
end

function Effects:ValidateSingletonFamilies()
    local errors = {}
    local function expect(ok, message)
        if not ok then errors[#errors + 1] = message end
    end
    local expected = {
        DEX_SPRING_HEEL = {"dex", 13, nil, "spring_heel"},
        DEX_MAGNUM_DEADEYE = {"dex", 15, "magnum", "magnum_deadeye"},
        STR_MELEE_REACH = {"str", 15, "crowbar", "melee_reach"},
        CON_RUSSIAN_ASSET = {"int", 13, "tetris", "russian_asset"}
    }
    for id, values in pairs(expected) do
        local feat = Feats[id]
        expect(feat ~= nil, "missing " .. id)
        if feat then
            expect(feat.governingAbilities[1] == values[1], id .. " governing ability")
            expect(feat.abilityRequirements[values[1]] == values[2], id .. " requirement")
            expect((feat.requiredCapabilityTags or {})[1] == values[3], id .. " capability")
            expect(feat.effectHandlerId == values[4], id .. " handler")
        end
    end

    local baseline = self:SingletonProfile({featIds = {}})
    local all = self:SingletonProfile({featIds = {
        "DEX_SPRING_HEEL", "DEX_MAGNUM_DEADEYE", "STR_MELEE_REACH",
        "CON_RUSSIAN_ASSET"
    }})
    expect(baseline.meleeReachMultiplier == 1, "baseline melee reach")
    expect(all.meleeReachMultiplier == 1.25
        and self.SingletonConfig.baseMeleeReach * all.meleeReachMultiplier == 120,
        "Long Reach trace distance")
    expect(baseline.jumpHeightMultiplier == 1 and all.jumpHeightMultiplier == 2,
        "Spring Heel height multiplier")
    expect(math.abs(all.jumpImpulseMultiplier * all.jumpImpulseMultiplier - 2) < 0.00001,
        "Spring Heel impulse produces 2x ballistic height")
    expect(baseline.tetrisOverfillMultiplier == 1
        and baseline.deathTetrisMaxSeconds == 60, "baseline Tetris profile")
    expect(all.tetrisOverfillMultiplier == 2 and all.deathTetrisMaxSeconds == 120,
        "Russian Asset Tetris profile")

    local deadeyeState = {
        featIds = {}, featQualificationAbilities = {dex = 15},
        classId = "rogue", secondaryAbilities = {}, capabilityTags = {}
    }
    local magnumPS = {inventory = {weapons = {{class = "weapon_357"}}}}
    local pistolPS = {inventory = {weapons = {{class = "weapon_pistol"}}}}
    expect(Progression:_FeatEligible(magnumPS, deadeyeState,
        Feats.DEX_MAGNUM_DEADEYE), "Deadeye legal with .357 access")
    expect(not Progression:_FeatEligible(pistolPS, deadeyeState,
        Feats.DEX_MAGNUM_DEADEYE), "Deadeye excludes actor without .357 access")

    local tetris = LOD.Tetris
    if tetris and tetris.RewardForLines then
        local rewards = {10, 30, 50, 80}
        for lines, reward in ipairs(rewards) do
            expect(self:TetrisOverfillReward(lines, {featIds = {}}) == reward,
                "baseline Tetris reward " .. lines)
            expect(self:TetrisOverfillReward(lines,
                {featIds = {"CON_RUSSIAN_ASSET"}}) == reward * 2,
                "Russian Asset Tetris reward " .. lines)
        end
    end

    return #errors == 0, errors
end

if Validation and not Validation.LODGateESingletonsWrapped then
    Validation.LODGateESingletonsWrapped = true
    local base = Validation.Run
    function Validation:Run(printResult)
        local baseOK, errors = base(self, false)
        errors = errors or {}
        local featOK, featErrors = Effects:ValidateSingletonFamilies()
        for _, message in ipairs(featErrors or {}) do
            errors[#errors + 1] = "Gate E singleton families: " .. message
        end
        local ok = baseOK and featOK and #errors == 0
        if printResult ~= false then
            if ok then
                print(string.format(
                    "[LOD:RPG] core RPG validation PASS — gate=%s gameplayEnabled=%s gateESMGHeat=true gateESingletons=true",
                    tostring(RPG.ImplementationGate), tostring(RPG.GameplayEnabled)))
            else
                ErrorNoHalt("[LOD:RPG] core RPG validation FAILED (" .. #errors .. " error(s))\n")
                for _, message in ipairs(errors) do
                    ErrorNoHalt("[LOD:RPG]  - " .. message .. "\n")
                end
            end
        end
        return ok, errors
    end
end

local function developerAllowed(ply)
    local cv = GetConVar("lod_developer_mode")
    return cv and cv:GetBool() and (not IsValid(ply) or ply:IsAdmin())
end

local TEST_IDS = {
    DEX_SPRING_HEEL = true,
    DEX_MAGNUM_DEADEYE = true,
    STR_MELEE_REACH = true,
    CON_RUSSIAN_ASSET = true
}

local function configure(ply, enabled)
    local run = LOD.RunManager
    local ps = run and run.GetPlayerState and run:GetPlayerState(ply) or nil
    local state = ps and ps.progressionState or nil
    if not state then return false, "RPG progression state is unavailable." end
    local kept = {}
    for _, id in ipairs(state.featIds or {}) do
        if not TEST_IDS[id] then kept[#kept + 1] = id end
    end
    state.featIds = kept
    state.featStackCounts = state.featStackCounts or {}
    for id in pairs(TEST_IDS) do state.featStackCounts[id] = nil end
    if enabled then
        for _, id in ipairs({
            "DEX_SPRING_HEEL", "DEX_MAGNUM_DEADEYE", "STR_MELEE_REACH",
            "CON_RUSSIAN_ASSET"
        }) do
            state.featIds[#state.featIds + 1] = id
            state.featStackCounts[id] = 1
        end
    end
    Progression:_RecomputeProgressionState(state)
    Progression:SyncPlayer(ply)
    if run.MarkUnranked then run:MarkUnranked("Gate E singleton feat test") end
    return true
end

local function resetTelemetry(ply, enabled)
    local stats = Effects.SingletonStats
    stats.jumpAttempts = 0
    stats.jumpBoosts = 0
    stats.lastJumpHeight = 0
    stats.lastJumpMultiplier = Rules:SpringHeelImpulseMultiplier(ply)
    stats.lastJumpImpulse = 0
    stats.lastJumpAddedImpulse = 0
    stats.lastMeleeReach = 0
    stats.meleeSwings = 0
    stats.expectedEnabled = enabled == true
    if not enabled then stats.baselineJumpHeight = 0 end
    local magnum = LOD.MagnumSuperExplosive
    if magnum and magnum.Stats then
        magnum.Stats.aimLocks = 0
        magnum.Stats.aimShots = 0
        magnum.Stats.aimCancels = 0
        magnum.Stats.lastAimHoldSeconds = nil
        magnum.Stats.lastAimLockElapsed = nil
    end
end

