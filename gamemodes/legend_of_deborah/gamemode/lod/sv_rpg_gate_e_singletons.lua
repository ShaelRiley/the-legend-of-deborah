function Rules:AimHoldSeconds(actorOrState)
    return Effects:SingletonProfile(stateFor(actorOrState)).aimHoldSeconds
end

function Rules:MagnumAimHoldSeconds(actorOrState)
    return Effects:SingletonProfile(stateFor(actorOrState)).magnumAimHoldSeconds
end

function Rules:SpringHeelImpulseMultiplier(actorOrState)
    return Effects:SingletonProfile(stateFor(actorOrState)).jumpImpulseMultiplier
end

function Rules:SpringHeelHeightMultiplier(actorOrState)
    return Effects:SingletonProfile(stateFor(actorOrState)).jumpHeightMultiplier
end

function Effects:SpringHeelAdditionalImpulse(actorOrState, takeoffImpulse)
    local takeoff = math.max(0, tonumber(takeoffImpulse) or 0)
    return takeoff * math.max(0, Rules:SpringHeelImpulseMultiplier(actorOrState) - 1)
end

function Rules:MeleeReachMultiplier(actorOrState)
    return Effects:SingletonProfile(stateFor(actorOrState)).meleeReachMultiplier
end

function Rules:MeleeReach(actorOrState, baseReach)
    return math.max(0, tonumber(baseReach) or 0) * self:MeleeReachMultiplier(actorOrState)
end

function Rules:TetrisOverfillMultiplier(actorOrState)
    return Effects:SingletonProfile(stateFor(actorOrState)).tetrisOverfillMultiplier
end

function Rules:DeathTetrisMaxSeconds(actorOrState)
    return Effects:SingletonProfile(stateFor(actorOrState)).deathTetrisMaxSeconds
end

function Effects:TetrisOverfillReward(lines, actorOrState)
    local tetris = LOD.Tetris
    local base = tetris and tetris.RewardForLines and tetris.RewardForLines(lines) or 0
    return base * Rules:TetrisOverfillMultiplier(actorOrState)
end

local function addSchemaField(name)
    local fields = RPG.Schema and RPG.Schema.DerivedStats
    if not fields then return end
    for _, existing in ipairs(fields) do
        if existing == name then return end
    end
    fields[#fields + 1] = name
end

