concommand.Add("lod_rpg_gate_e_singletons_status", function(ply)
    if not developerAllowed(ply) or not IsValid(ply) then return end
    local profile = Effects:SingletonProfile(Rules:ProgressionState(ply))
    local stats = Effects.SingletonStats
    local magnum = LOD.MagnumSuperExplosive
    local magnumStats = magnum and magnum.Stats or {}
    local rewards = {}
    for lines = 1, 4 do
        rewards[#rewards + 1] = tostring(Effects:TetrisOverfillReward(lines, ply))
    end
    local expectedReach = BASE_MELEE_REACH * profile.meleeReachMultiplier
    local expectedBoosts = profile.springHeel and 1 or 0
    local acceptance = (stats.jumpAttempts or 0) >= 1
        and (stats.jumpBoosts or 0) >= expectedBoosts
        and (not profile.springHeel or (stats.jumpBoosts or 0) >= 1)
        and (profile.springHeel or (stats.jumpBoosts or 0) == 0)
        and (stats.meleeSwings or 0) >= 1
        and math.abs((stats.lastMeleeReach or 0) - expectedReach) < 0.01
        and (magnumStats.aimLocks or 0) >= 1
    local jumpRatio = (stats.baselineJumpHeight or 0) > 0
        and (stats.lastJumpHeight or 0) / stats.baselineJumpHeight or 0
    local line = string.format(
        "spring=%s impulse=x%.4f jumps=%d boosts=%d lastHeight=%.1f baselineHeight=%.1f ratio=%.2f deadeye=%s hold=%.2fs locks=%d lastLock=%.3fs longReach=%s reach=%.1f lastReach=%.1f swings=%d russian=%s rewards=%s deathCap=%ds acceptance=%s",
        tostring(profile.springHeel), profile.jumpImpulseMultiplier,
        stats.jumpAttempts or 0, stats.jumpBoosts or 0, stats.lastJumpHeight or 0,
        stats.baselineJumpHeight or 0, jumpRatio,
        tostring(profile.deadeye), 0.50,
        magnumStats.aimLocks or 0, magnumStats.lastAimLockElapsed or 0,
        tostring(profile.longReach), expectedReach,
        stats.lastMeleeReach or 0, stats.meleeSwings or 0,
        tostring(profile.russianAsset), table.concat(rewards, "/"),
        profile.deathTetrisMaxSeconds, acceptance and "PASS" or "WAITING")
    print("[LOD:RPG-E] " .. line)
    ply:ChatPrint(line)
end)

