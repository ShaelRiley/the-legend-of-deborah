#!/usr/bin/env python3
"""Build the authored GPS praise bank offline with FFmpeg's Flite voice."""
from pathlib import Path
import array
import json
import re
import subprocess
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[1]
ROOM = ROOT / 'docs/lore/room/gps_navigation_praise_20261013.md'
lines = re.findall(r'^\d+\. (.+)$', ROOM.read_text(), re.M)
assert len(lines) == 16 and len(set(lines)) == 16
RATE = 22050
pcm = array.array('h')
markers = []
with tempfile.TemporaryDirectory(prefix='lod-gps-praise-') as scratch:
    scratch = Path(scratch)
    for i, text in enumerate(lines, 1):
        source, wav = scratch / f'{i}.txt', scratch / f'{i}.wav'
        source.write_text(text)
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i',
                        f'flite=textfile={source}:voice=kal', '-ar', str(RATE),
                        '-ac', '1', '-c:a', 'pcm_s16le', str(wav)], check=True)
        with wave.open(str(wav), 'rb') as audio:
            assert audio.getframerate() == RATE and audio.getnchannels() == 1
            samples = array.array('h', audio.readframes(audio.getnframes()))
        assert max(map(abs, samples)) > 100 and 1 < len(samples) / RATE < 10
        markers.append((len(pcm) / RATE, len(samples) / RATE))
        pcm.extend(samples)
        pcm.extend([0] * round(.04 * RATE))
    peak = max(map(abs, pcm))
    pcm = array.array('h', (round(v * (32767 * .85 / peak)) for v in pcm))
    bank = scratch / 'bank.wav'
    with wave.open(str(bank), 'wb') as wav:
        wav.setnchannels(1); wav.setsampwidth(2); wav.setframerate(RATE)
        wav.writeframes(pcm.tobytes())
    target = ROOT / 'gamemodes/legend_of_deborah/content/sound/lod/gps_praise_bank.mp3'
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(bank), '-c:a', 'libmp3lame',
                    '-b:a', '64k', '-map_metadata', '-1', str(target)], check=True)
body = ['-- Generated by tools/build_gps_praise.py from the eight-writer room.',
        'LOD.GPSPraise={Bank="sound/lod/gps_praise_bank.mp3",Lines={']
body.extend('    ' + json.dumps(line) + ',' for line in lines)
body.append('},Markers={')
body.extend(f'    praise_{i:02}={{{start:.6f},{duration:.6f}}},' for i, (start, duration) in enumerate(markers, 1))
body.append('}}')
(ROOT / 'gamemodes/legend_of_deborah/gamemode/lod/sh_gps_praise.lua').write_text('\n'.join(body) + '\n')
print(f'GPS_PRAISE_BUILD: 16 authored clips; {len(pcm)/RATE:.2f}s; Flite kal; mono 22050Hz; peak normalized; {target.stat().st_size} bytes')
